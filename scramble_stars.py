"""Scramble 1981 starfield blinking, translated from MAME galaxold_v.cpp.

Star *locations* and RGB values are generated by scramble_stars() in
scroll_viewer.py, using the Galaxian star LFSR. Only the 4-phase visibility
mask varies with time. Scramble's 555 timer (MAME start_stars_blink_timer)
sets a phase every *831 milliseconds*; unlike Galaxian, stars do not scroll.

The formula and integer conversion below follow MAME precisely:
    int period_in_ms = 693 * (ra + 2.0 * rb) * c
    ra=100000, rb=10000, c=0.00001
Each logical update is 16.5ms at the 16000/264 Hz original refresh rate.
"""
from __future__ import annotations

BLINK_PERIOD_MS = int(693 * (100000 + 2.0 * 10000) * 0.00001)   # 831
FRAME_TIME_TWICE_MS = 33                # each frame = 33/2 ms = 16.5ms


def blink_state(frame: int) -> int:
    """Original star blink phase (0..3), keyed to logical game frames.

    The timer begins at the first starfield draw; we use frame zero as the
    origin of our test viewer. Exact starting phase vs MAME still depends on
    aligning the first active frame of gameplay/attract mode.
    """
    return (max(0, frame) * FRAME_TIME_TWICE_MS // (2 * BLINK_PERIOD_MS)) & 3


def star_visible(flags: int, phase: int) -> bool:
    """MAME scrambold_draw_stars filters by color bit 0, bit 2, y bit 1.

    flags are packed once by scroll_viewer.scramble_stars():
      0x01 = (star RGB colour index & 1) != 0
      0x02 = (star RGB colour index & 4) != 0
      0x04 = (hardware star Y & 2) != 0
    Phase 3 shows all stars. No random twinkling or moving the stars.
    """
    p = phase & 3
    return p == 3 or bool(flags & (1 << p))
